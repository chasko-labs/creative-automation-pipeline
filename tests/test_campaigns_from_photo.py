def test_from_photo_route_registered_when_fastapi_present():
    """Bare-python-safe: when FastAPI is present the routes exist; otherwise skip cleanly."""
    if not HAS_FASTAPI:
        pytest.skip("FastAPI not installed -- endpoint tests skip by design")
    paths = {getattr(r, "path", "") for r in app.routes}
    assert "/campaigns/from-photo" in paths
    assert "/campaigns/from-prompt" in paths
